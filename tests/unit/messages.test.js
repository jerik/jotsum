const assert = require('assert');
const fs = require('fs');
let now = 0, sequence = 0;
const timers = new Map();
Date.now = () => now;
global.setTimeout = (run, delay) => { timers.set(++sequence, { run, at: now + delay }); return sequence; };
global.clearTimeout = id => timers.delete(id);
function tick(ms) { now += ms; for (const [id, timer] of [...timers]) if (timer.at <= now) { timers.delete(id); timer.run(); } }
const nodes = { messages: mockUiElement(), 'more-actions': mockUiElement(), sidebar: mockUiElement() };
nodes['more-actions'].hidden = true;
document.getElementById = id => nodes[id] || null;
document.createElement = tag => mockUiElement(tag);
document.body.classList = mockUiElement().classList;
const { show_message, handle_header_keys, save_store, import_sheet_text } = require('../../jotsum.js');
const stack = nodes.messages.children;
const clear = () => { while (stack.length) stack[0].children.at(-1).emit('click'); };
let message = show_message({ tone: 'success', text: 'Saved' });
assert.strictEqual(message.node.getAttribute('role'), 'status');
tick(4999); assert.strictEqual(stack.length, 1);
tick(1); assert.strictEqual(stack.length, 0);
for (const [enter, leave] of [['mouseenter', 'mouseleave'], ['focusin', 'focusout']]) {
    message = show_message({ tone: 'success', text: enter });
    tick(2000); message.node.emit(enter); tick(10000);
    assert.strictEqual(stack.length, 1);
    message.node.emit(leave, { relatedTarget: null }); tick(2999);
    assert.strictEqual(stack.length, 1); tick(1); assert.strictEqual(stack.length, 0);
}
for (const tone of ['info', 'warning', 'error']) {
    message = show_message({ tone, text: tone });
    assert.strictEqual(message.node.getAttribute('role'), tone === 'error' ? 'alert' : 'status');
}
tick(100000); assert.strictEqual(stack.length, 3); clear();
show_message({ tone: 'warning', text: 'old' });
show_message({ tone: 'success', text: 'drop' });
show_message({ text: 'middle' });
show_message({ text: 'new' });
assert.deepStrictEqual(stack.map(n => n.children[1].textContent), ['old', 'middle', 'new']);
show_message({ text: 'fourth' });
assert.deepStrictEqual(stack.map(n => n.children[1].textContent), ['middle', 'new', 'fourth']);
handle_header_keys({ key: 'Escape' });
assert.strictEqual(stack.at(-1).children[1].textContent, 'new');
nodes['more-actions'].hidden = false;
handle_header_keys({ key: 'Escape' }); assert.strictEqual(stack.length, 2);
document.body.classList.add('drawer-open');
handle_header_keys({ key: 'Escape' }); assert.strictEqual(stack.length, 2);
clear();
message = show_message({ tone: 'success', text: 'duplicate' }); tick(4000);
assert.strictEqual(show_message({ tone: 'success', text: 'duplicate' }), message);
tick(4999); assert.strictEqual(stack.length, 1); tick(1); assert.strictEqual(stack.length, 0);
(async () => {
    let ran = 0;
    message = show_message({ tone: 'success', text: 'action', action: { label: 'Run', run: () => { ran++; } } });
    tick(100000); assert.strictEqual(stack.length, 1);
    assert.strictEqual(message.node.children[2].tagName, 'BUTTON');
    assert.strictEqual(document.activeElement, undefined);
    message.node.children[2].emit('click'); await Promise.resolve();
    assert.strictEqual(ran, 1); assert.strictEqual(stack.length, 0);
    const set = window.localStorage.setItem;
    window.localStorage.setItem = () => { throw Error('full'); };
    save_store([{ id: 'A', lines: ['one'] }], 'A');
    assert.strictEqual(stack.length, 1);
    assert.strictEqual(stack[0].getAttribute('role'), 'alert');
    assert.strictEqual(stack[0].children[2].textContent, 'Export');
    clear(); save_store([{ id: 'A', lines: ['two'] }], 'A'); assert.strictEqual(stack.length, 0);
    window.localStorage.setItem = set;
    save_store([{ id: 'A', lines: ['three'] }], 'A');
    window.localStorage.setItem = () => { throw Error('full'); };
    save_store([{ id: 'A', lines: ['four'] }], 'A'); assert.strictEqual(stack.length, 1);
    window.localStorage.setItem = set; clear();
    import_sheet_text('x'.repeat(256 * 1024 + 1));
    assert.match(stack[0].children[1].textContent, /256 KiB and 2000 lines/);
    assert.strictEqual(stack[0].getAttribute('role'), 'alert');
    clear();
    const html = fs.readFileSync('jotsum.html', 'utf8');
    assert.match(html, /id="messages" aria-live="polite"/);
    assert.match(html, /#messages\s*{\s*position: fixed; z-index: 40/);
    assert.doesNotMatch(html, /id="(?:sharing-notice|file-notice|remote-change-notice|shared-sheet-banner)"/);
    console.log('Message lifetime, pause, actions, roles, stack, Esc and storage failure checks passed!');
})().catch(error => { console.error(error); process.exitCode = 1; });
